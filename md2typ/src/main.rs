//! md2typ — turn scenario-flavoured Markdown into a Typst document that
//! renders through `template/scenario.typ`.
//!
//!     md2typ scenarios/heart-of-the-foe.md -o build/heart-of-the-foe.typ
//!
//! The Markdown dialect is documented in DIALECT.md.

mod block;
mod front;
mod inline;
mod statblock;

use front::Value;
use inline::{inline, strlit};
use std::io::Write;
use std::process::ExitCode;

const DEFAULT_TEMPLATE: &str = "/template/scenario.typ";

fn usage() -> &'static str {
    "usage: md2typ <input.md> [-o <output.typ>] [--template <path>]\n\
     \n\
     Reads a scenario in the Markdown dialect described in DIALECT.md and\n\
     writes a Typst source file. With no -o, writes to stdout.\n"
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let mut input: Option<String> = None;
    let mut output: Option<String> = None;
    let mut template: Option<String> = None;

    let mut i = 0;
    while i < args.len() {
        match args[i].as_str() {
            "-h" | "--help" => {
                print!("{}", usage());
                return ExitCode::SUCCESS;
            }
            "-o" | "--output" => {
                i += 1;
                output = args.get(i).cloned();
            }
            "--template" => {
                i += 1;
                template = args.get(i).cloned();
            }
            a if a.starts_with('-') => {
                eprintln!("md2typ: unknown option `{a}`\n\n{}", usage());
                return ExitCode::FAILURE;
            }
            a => input = Some(a.to_string()),
        }
        i += 1;
    }

    let Some(input) = input else {
        eprint!("{}", usage());
        return ExitCode::FAILURE;
    };

    let src = match std::fs::read_to_string(&input) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("md2typ: cannot read {input}: {e}");
            return ExitCode::FAILURE;
        }
    };

    let typ = match render(&src, template.as_deref()) {
        Ok(t) => t,
        Err(e) => {
            eprintln!("md2typ: {input}: {e}");
            return ExitCode::FAILURE;
        }
    };

    match output {
        Some(path) => {
            if let Some(parent) = std::path::Path::new(&path).parent() {
                let _ = std::fs::create_dir_all(parent);
            }
            if let Err(e) = std::fs::write(&path, typ) {
                eprintln!("md2typ: cannot write {path}: {e}");
                return ExitCode::FAILURE;
            }
        }
        None => {
            let _ = std::io::stdout().write_all(typ.as_bytes());
        }
    }
    ExitCode::SUCCESS
}

fn render(src: &str, template_override: Option<&str>) -> Result<String, String> {
    let (front_src, body_src) = front::split(src);
    let front = match front_src {
        Some(f) => front::parse(&f)?,
        None => front::Front::new(),
    };

    let get = |k: &str| front.get(k).and_then(|v| v.as_str()).map(|s| s.to_string());
    let list = |k: &str| front.get(k).map(|v| v.as_list()).unwrap_or_default();

    let template = template_override
        .map(|s| s.to_string())
        .or_else(|| get("template"))
        .unwrap_or_else(|| DEFAULT_TEMPLATE.to_string());

    let mut out = String::new();
    out.push_str("// Generated by md2typ. Edit the Markdown source, not this file.\n");
    out.push_str(&format!("#import {}: *\n\n", strlit(&template)));
    out.push_str("#show: scenario.with(\n");

    // plain string arguments
    for (key, arg) in [
        ("title", "title"),
        ("author", "author"),
        ("series", "series"),
        ("number", "number"),
        ("tier", "tier"),
        ("banner", "banner"),
        ("art", "art"),
    ] {
        if let Some(v) = get(key) {
            out.push_str(&format!("  {arg}: {},\n", strlit(&v)));
        }
    }
    if let Some(v) = get("start-page").or_else(|| get("start_page")) {
        out.push_str(&format!("  start-page: {v},\n"));
    }
    if let Some(v) = get("cover") {
        out.push_str(&format!("  cover: {},\n", v == "true" || v == "yes"));
    }

    // content arguments
    let credits = list("credits");
    if !credits.is_empty() {
        out.push_str("  credits: (\n");
        for c in &credits {
            out.push_str(&format!("    [{}],\n", inline(c)));
        }
        out.push_str("  ),\n");
    }

    let contents = list("contents");
    if !contents.is_empty() {
        out.push_str("  contents: (\n");
        for row in &contents {
            let (label, page) = match row.rsplit_once('|') {
                Some((l, p)) => (l.trim(), p.trim()),
                None => (row.as_str(), ""),
            };
            out.push_str(&format!("    ({}, {}),\n", strlit(label), strlit(page)));
        }
        out.push_str("  ),\n");
    }

    let tags = list("tags");
    if !tags.is_empty() {
        out.push_str("  tags: (\n");
        for t in &tags {
            out.push_str(&format!("    [{}],\n", inline(t)));
        }
        out.push_str("  ),\n");
    }

    for (key, arg) in [
        ("resources", "resources"),
        ("how-to-play", "how-to-play"),
        ("how_to_play", "how-to-play"),
        ("legal", "legal"),
    ] {
        if let Some(Value::Text(t)) = front.get(key) {
            out.push_str(&format!("  {arg}: [\n{}  ],\n", indent(&block::convert(t), 4)));
        } else if let Some(v) = get(key) {
            out.push_str(&format!("  {arg}: [{}],\n", inline(&v)));
        }
    }

    out.push_str(")\n\n");
    out.push_str(&block::convert(&body_src));
    Ok(out)
}

fn indent(s: &str, n: usize) -> String {
    let pad = " ".repeat(n);
    s.lines()
        .map(|l| if l.is_empty() { String::new() } else { format!("{pad}{l}") })
        .collect::<Vec<_>>()
        .join("\n")
        + "\n"
}
